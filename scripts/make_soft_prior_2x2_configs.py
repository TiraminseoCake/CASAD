"""Generate the soft-prior 2x2 pilot YAMLs from the verified *_cf_val.yaml bases.

Derived-YAML approach on purpose: the launcher is not assumed to support
arbitrary config overrides, so every pilot condition gets its own complete
YAML file (the same mechanism the noalign ablation already used).

The base YAML is parsed and DEEP-MERGED with the override dict, then re-emitted
as a single clean document. Appending a second `PICAAD:` block to the same file
would NOT work: PyYAML keeps only the last duplicate mapping key and silently
discards the earlier one, so the base's settings would be lost.

Each generated file differs from its base in exactly these keys:
    PICAAD.PRIOR.SMOOTH_RHO             rho      (the pilot axis)
    PICAAD.EFF_GATE_FLOOR               g_min    (the pilot axis)
    PICAAD.ENABLE_PRIOR_LOSS            False    (fixed condition)
    PICAAD.START_CLS_EPOCH              81       (fixed condition)
    PICAAD.SCORING.USE_COUNTERFACTUAL   False    (CF fully off)
    PICAAD.SCORING.SCORE_GAMMA          0.0      (housekeeping; CF never computed)
    SEEDS                               [0]      (pilot scope)

Everything else - model size, LR, batch, warmup, VAL/EVAL blocks,
PERM_PAIRS_PER_BATCH=0, CALIBRATE=False - is inherited unchanged, which the
accompanying test asserts key by key.

Run:  python scripts/make_soft_prior_2x2_configs.py
"""
import copy
import os
import sys

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO not in sys.path:
    sys.path.insert(0, REPO)

CONDITIONS = [
    ("t0", 0.0, 0.0),
    ("t1", 0.05, 0.0),
    ("t2", 0.0, 0.05),
    ("t3", 0.05, 0.05),
]

BASES = {
    "psm": "scripts/configs/psm_cf_val.yaml",
    "smd": "scripts/configs/smd_cf_val.yaml",
    "swat": "scripts/configs/swat_cf_val.yaml",
}

OUT_DIR = "scripts/configs/soft_prior_2x2"

HEADER = """# soft-prior 2x2 pilot - condition {cond_upper}: rho={rho:g}, g_min={gmin:g}
#
# GENERATED by scripts/make_soft_prior_2x2_configs.py from {base}
# DO NOT EDIT BY HAND - regenerate instead.
#
# Fixed for every condition: prediction loss only (ENABLE_PRIOR_LOSS=False,
# START_CLS_EPOCH=81 > MAX_EPOCH=80 so cstruct never activates,
# PERM_PAIRS_PER_BATCH=0, all auxiliary losses off), CALIBRATE=False,
# USE_COUNTERFACTUAL=False so CF profile fitting and CF forward are never
# called. Evaluate best_val only, with: scripts/eval_ckpt.py --cf off
#
# The causal prior stays in initialization and in the forward pass. Only the two
# forward relaxations differ across conditions:
#   PICAAD.PRIOR.SMOOTH_RHO  rho    p_rho = (1-rho)*te_prior_weight + rho/(tau_max*N)
#   PICAAD.EFF_GATE_FLOOR    g_min  G_floor = g_min + (1-g_min)*G_native
# Neither is in state_dict, so all four conditions share one initial state hash.
#
# Protocol: docs/soft_prior_2x2_protocol.md
#
# NOTE: utils/parser.py:_DATASET_DEFAULT_LR overrides SOLVER.BASE_LR from
# DATA.NAME unless the caller passes SOLVER.BASE_LR on the CLI, so the effective
# LR is PSM 5e-05 / SMD 5e-04 / SWaT 5e-04 regardless of the value below.
# Left as inherited on purpose: unchanged launcher behaviour.
"""


def deep_merge(base: dict, over: dict) -> dict:
    """Recursive dict merge; `over` wins at the leaves."""
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def overrides(rho: float, gmin: float) -> dict:
    return {
        "SEEDS": [0],
        "PICAAD": {
            "ENABLE_PRIOR_LOSS": False,
            "START_CLS_EPOCH": 81,
            "EFF_GATE_FLOOR": gmin,
            "PRIOR": {"SMOOTH_RHO": rho},
            "INTERVENTION": {"PERM_PAIRS_PER_BATCH": 0},
            "SCORING": {
                "CALIBRATE": False,
                "USE_COUNTERFACTUAL": False,
                "SCORE_GAMMA": 0.0,
            },
        },
        "SOLVER": {"MAX_EPOCH": 80},
        "VAL": {"ENABLE": True, "FRAC": 0.2, "SELECTION_METRIC": "pred_mae"},
    }


def main():
    written = []
    for ds, base_rel in BASES.items():
        with open(os.path.join(REPO, base_rel)) as f:
            base = yaml.safe_load(f)
        for cond, rho, gmin in CONDITIONS:
            merged = deep_merge(base, overrides(rho, gmin))
            body = yaml.safe_dump(merged, default_flow_style=False, sort_keys=True)
            # a re-parse must round-trip exactly: no duplicate-key loss
            assert yaml.safe_load(body) == merged, f"{ds}/{cond}: YAML round-trip mismatch"
            out_rel = f"{OUT_DIR}/{ds}_sp2x2_{cond}.yaml"
            out_path = os.path.join(REPO, out_rel)
            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            with open(out_path, "w") as f:
                f.write(HEADER.format(cond_upper=cond.upper(), rho=rho, gmin=gmin, base=base_rel))
                f.write("\n")
                f.write(body)
            written.append(out_rel)
    for p in written:
        print(f"wrote {p}")
    print(f"\n{len(written)} files")


if __name__ == "__main__":
    main()
