"""Generate the P3 structural-ablation YAMLs from the verified *_cf_val.yaml bases.

Same derived-YAML mechanism as scripts/make_soft_prior_2x2_configs.py (exp/soft-prior-2x2): the base is parsed,
DEEP-MERGED with an override dict and re-emitted as one document (appending a second PICAAD: block would
silently drop the first under PyYAML's duplicate-key handling).

Common to every arm (prediction-only objective, docs/p3_structural_ablation_protocol.md section 1):
    PICAAD.ENABLE_PRIOR_LOSS                 False
    PICAAD.START_CLS_EPOCH                   99999     (never; 81 would depend on MAX_EPOCH=80)
    PICAAD.INTERVENTION.PERM_PAIRS_PER_BATCH 0
    PICAAD.SCORING.CALIBRATE                 False
    PICAAD.SCORING.USE_COUNTERFACTUAL        False     (eval with --cf off; CF never computed)
    PICAAD.SCORING.SCORE_GAMMA               0.0
    SOLVER.MAX_EPOCH 80, VAL.ENABLE True, VAL.FRAC 0.2, VAL.SELECTION_METRIC pred_mae
Arm keys (the ONLY keys that differ between arms of one dataset):
    a  PCMCI+ prior          PRIOR.TYPE pcmci  PRIOR.RANDOMIZE none                  DYNAMIC_GRAPH True
    n  no prior              PRIOR.TYPE none   PRIOR.RANDOMIZE none                  DYNAMIC_GRAPH True
    r  matched random prior  PRIOR.TYPE pcmci  PRIOR.RANDOMIZE degree_preserving_v1  DYNAMIC_GRAPH True
    d  delta removed         PRIOR.TYPE pcmci  PRIOR.RANDOMIZE none                  DYNAMIC_GRAPH False

Run:  python scripts/make_p3_configs.py
"""
import copy
import os
import sys

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO not in sys.path:
    sys.path.insert(0, REPO)

ARMS = {
    'a': {'label': 'PCMCI+ prior', 'PRIOR': {'TYPE': 'pcmci', 'RANDOMIZE': 'none'}, 'DYNAMIC_GRAPH': True},
    'n': {'label': 'no prior', 'PRIOR': {'TYPE': 'none', 'RANDOMIZE': 'none'}, 'DYNAMIC_GRAPH': True},
    'r': {'label': 'sparsity/lag-matched random prior', 'PRIOR': {'TYPE': 'pcmci', 'RANDOMIZE': 'degree_preserving_v1'},
          'DYNAMIC_GRAPH': True},
    'd': {'label': 'dynamic correction removed', 'PRIOR': {'TYPE': 'pcmci', 'RANDOMIZE': 'none'}, 'DYNAMIC_GRAPH': False},
}
ARM_KEYS = ('PICAAD.PRIOR.TYPE', 'PICAAD.PRIOR.RANDOMIZE', 'PICAAD.DYNAMIC_GRAPH')

BASES = {
    'psm': 'scripts/configs/psm_cf_val.yaml',
    'smd': 'scripts/configs/smd_cf_val.yaml',
    'swat': 'scripts/configs/swat_cf_val.yaml',
}
OUT_DIR = 'scripts/configs/p3_structural'

HEADER = """# P3 structural ablation - arm {arm} ({label})
#
# GENERATED by scripts/make_p3_configs.py from {base}
# DO NOT EDIT BY HAND - regenerate instead.
#
# Prediction-only objective for every arm: ENABLE_PRIOR_LOSS=False, START_CLS_EPOCH=99999 (CRS loss never),
# PERM_PAIRS_PER_BATCH=0 (no intervention loss, cls_ref never updated from interventions), auxiliary losses off.
# CALIBRATE=False, USE_COUNTERFACTUAL=False: evaluate best_val with scripts/eval_ckpt.py --cf off --calibrate off.
# Arm keys: PRIOR.TYPE={ptype}  PRIOR.RANDOMIZE={rand}  DYNAMIC_GRAPH={dyn}
#
# Protocol: docs/p3_structural_ablation_protocol.md
#
# NOTE: utils/parser.py:_DATASET_DEFAULT_LR sets the effective LR from DATA.NAME (PSM 5e-05, SMD 5e-04,
# SWaT 5e-04) unless SOLVER.BASE_LR is passed on the CLI; identical for all arms.
"""


def deep_merge(base: dict, over: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def overrides(arm: str) -> dict:
    a = ARMS[arm]
    return {
        'PICAAD': {
            'ENABLE_PRIOR_LOSS': False,
            'START_CLS_EPOCH': 99999,
            'DYNAMIC_GRAPH': a['DYNAMIC_GRAPH'],
            'PRIOR': dict(a['PRIOR']),
            'INTERVENTION': {'PERM_PAIRS_PER_BATCH': 0},
            'SCORING': {'CALIBRATE': False, 'USE_COUNTERFACTUAL': False, 'SCORE_GAMMA': 0.0},
        },
        'SOLVER': {'MAX_EPOCH': 80},
        'VAL': {'ENABLE': True, 'FRAC': 0.2, 'SELECTION_METRIC': 'pred_mae', 'SAVE_EVERY_EPOCH': False, 'SAVE_EVERY_N': 0},
    }


def generated_configs():
    """{relative path: (dataset, arm, merged dict, base relative path)} - used by the generator and the tests."""
    out = {}
    for ds, base_rel in BASES.items():
        with open(os.path.join(REPO, base_rel)) as f:
            base = yaml.safe_load(f)
        for arm in ARMS:
            out[f'{OUT_DIR}/{ds}_p3_{arm}.yaml'] = (ds, arm, deep_merge(base, overrides(arm)), base_rel)
    return out


def main():
    for rel, (ds, arm, merged, base_rel) in generated_configs().items():
        body = yaml.safe_dump(merged, default_flow_style=False, sort_keys=True)
        assert yaml.safe_load(body) == merged, f'{rel}: YAML round-trip mismatch'
        a = ARMS[arm]
        path = os.path.join(REPO, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as f:
            f.write(HEADER.format(arm=arm.upper(), label=a['label'], base=base_rel, ptype=a['PRIOR']['TYPE'],
                                  rand=a['PRIOR']['RANDOMIZE'], dyn=a['DYNAMIC_GRAPH']))
            f.write('\n')
            f.write(body)
        print(f'wrote {rel}')


if __name__ == '__main__':
    main()
